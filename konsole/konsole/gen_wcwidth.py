#!/usr/bin/env python3
#
# Generate konsole_wcwidth_table.h, the column width tables used by
# konsole_wcwidth(), from the Unicode Character Database.
#
#   gen_wcwidth.py [UCD-directory] > konsole_wcwidth_table.h
#
# The directory must contain UnicodeData.txt, EastAsianWidth.txt,
# PropList.txt and emoji-data.txt of one Unicode version (the default,
# /usr/share/unicode, is where most distributions install them; TeX Live
# ships a copy in texmf-dist/tex/generic/unicode-data).
#
# The rules follow glibc's wcwidth(), which is what most programs running
# in the terminal use to lay out their output:
#
#   width 0: nonspacing and enclosing marks (Mn, Me), format characters
#            (Cf) except the visible prepended concatenation marks
#            (U+0600 ARABIC NUMBER SIGN etc.) and U+00AD SOFT HYPHEN, and
#            the conjoining Hangul medial vowels and final consonants
#            (U+1160..U+11FF, U+D7B0..U+D7FF) which merge with the
#            preceding initial consonant;
#   width 2: East Asian Wide (W) and Fullwidth (F) characters, including
#            the unassigned code points that UAX #11 defaults to W, and
#            characters with Emoji_Presentation (already W since
#            Unicode 9) except the regional indicators, which pair up
#            into flags and are N;
#   width 1: everything else.
#
# Spacing marks (Mc) count as one column like in glibc. Control characters
# are not in the tables; konsole_wcwidth() handles them itself.
#
# This script is public domain, like the original konsole_wcwidth.cpp.

import os
import re
import sys

ucd = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/unicode'
MAX = 0x10FFFF


def ucd_lines(name):
    with open(os.path.join(ucd, name), encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                yield [field.strip() for field in line.split(';')]


def code_range(field):
    if '..' in field:
        first, last = field.split('..')
        return int(first, 16), int(last, 16)
    return int(field, 16), int(field, 16)


def version(name):
    with open(os.path.join(ucd, name), encoding='utf-8') as f:
        m = re.search(r'-(\d+\.\d+\.\d+)\.txt', f.readline())
    return m.group(1) if m else 'unknown'


# General category of every code point (UnicodeData.txt; "First>"/"Last>"
# pairs describe ranges).
category = {}
first = None
for fields in ucd_lines('UnicodeData.txt'):
    cp, name, cat = int(fields[0], 16), fields[1], fields[2]
    if name.endswith(', First>'):
        first = cp
        continue
    if name.endswith(', Last>'):
        for c in range(first, cp + 1):
            category[c] = cat
        continue
    category[cp] = cat

# East Asian Width, with the defaults of UAX #11 for unlisted code points.
eaw = {}
for lo, hi in ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
               (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)):
    for c in range(lo, hi + 1):
        eaw[c] = 'W'
for fields in ucd_lines('EastAsianWidth.txt'):
    lo, hi = code_range(fields[0])
    for c in range(lo, hi + 1):
        eaw[c] = fields[1]


def prop(name, wanted):
    s = set()
    for fields in ucd_lines(name):
        if fields[1] == wanted:
            lo, hi = code_range(fields[0])
            s.update(range(lo, hi + 1))
    return s


prepended = prop('PropList.txt', 'Prepended_Concatenation_Mark')
regional = prop('PropList.txt', 'Regional_Indicator')
emoji_presentation = prop('emoji-data.txt', 'Emoji_Presentation')


def width(c):
    cat = category.get(c, 'Cn')
    if cat in ('Mn', 'Me'):
        return 0
    if cat == 'Cf' and c != 0x00AD and c not in prepended:
        return 0
    if 0x1160 <= c <= 0x11FF or 0xD7B0 <= c <= 0xD7FF:
        return 0
    if eaw.get(c, 'N') in ('W', 'F'):
        return 2
    if c in emoji_presentation and c not in regional:
        return 2
    return 1


def intervals(pred):
    out = []
    for c in range(0, MAX + 1):
        if 0xD800 <= c <= 0xDFFF:
            continue                    # surrogates never reach wcwidth
        if c < 0xA0 and c != 0xAD:
            continue                    # ASCII and C0/C1 are handled in code
        if pred(c):
            if out and out[-1][1] == c - 1:
                out[-1][1] = c
            else:
                out.append([c, c])
    return out


def table(name, ivs):
    print('static const struct interval %s[] = {' % name)
    for i in range(0, len(ivs), 3):
        row = ivs[i:i + 3]
        print('  ' + ' '.join('{ 0x%05X, 0x%05X },' % (lo, hi)
                              for lo, hi in row))
    print('};')
    print()


zero = intervals(lambda c: width(c) == 0)
wide = intervals(lambda c: width(c) == 2)

print('/* Generated by gen_wcwidth.py from the Unicode %s Character Database.'
      % version('EastAsianWidth.txt'))
print('   Do not edit; rerun the script with newer UCD files instead. */')
print()
print('#define KONSOLE_WCWIDTH_UNICODE_VERSION "%s"'
      % version('EastAsianWidth.txt'))
print()
print('/* Characters of width 0: Mn, Me, Cf (but U+00AD and the prepended')
print('   concatenation marks) and conjoining Hangul medial/final jamo. */')
table('zero_width', zero)
print('/* Characters of width 2: East Asian Wide and Fullwidth, plus')
print('   Emoji_Presentation except the regional indicators. */')
table('double_width', wide)
